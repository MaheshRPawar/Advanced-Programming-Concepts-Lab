# List
# Empty List
list1 = []
print(list1)

# Number List
list2 = [10, 20, 30, 40]
print(list2)

# Name List
names = ["Rahul", "Amit", "Priya"]
print(names)

# Mixed List
student = [101, "Rahul", 92.5, True]
print(student)

# Index
fruits = ["Apple", "Banana", "Mango", "Orange"]
print(fruits[0])
print(fruits[1])
print(fruits[2])
print(fruits[3])

# Negative Index
print(fruits[-1])
print(fruits[-2])

# Append
fruits.append("Grapes")
print(fruits)

# Insert
fruits.insert(1, "Pineapple")
print(fruits)

# Remove
fruits.remove("Banana")
print(fruits)

# Pop
fruits.pop()
print(fruits)

# Length
print(len(fruits))

# Sort
numbers = [40, 10, 30, 20]
numbers.sort()
print(numbers)

# Reverse
numbers.reverse()
print(numbers)
