# Tuple
# Empty Tuple
tuple1 = ()
print(tuple1)

# Number Tuple
tuple2 = (10, 20, 30, 40)
print(tuple2)

# Name Tuple
names = ("Rahul", "Amit", "Priya")
print(names)

# Mixed Tuple
student = (101, "Rahul", 92.5, True)
print(student)

# Index
fruits = ("Apple", "Banana", "Mango", "Orange")
print(fruits[0])
print(fruits[1])
print(fruits[2])
print(fruits[3])

# Negative Index
print(fruits[-1])
print(fruits[-2])

# Length
print(len(fruits))

# Count
numbers = (10, 20, 30, 20, 40)
print(numbers.count(20))

# Index
print(numbers.index(30))

# Join
t1 = (1, 2, 3)
t2 = (4, 5, 6)
print(t1 + t2)
